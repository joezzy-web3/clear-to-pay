#!/usr/bin/env bash
# Baseline comparison: every invoice attack against "allowlist + limits" and against Clear to Pay.
# Runs the test in src/baseline_tests.rs and saves the table to docs/baseline.md.
set -euo pipefail
cd "$(dirname "$0")/.."
out=$(cargo test -q --lib baseline_comparison -- --nocapture 2>&1)
table=$(echo "$out" | grep -E '^\|')
summary=$(echo "$out" | grep -E '^Attacks paid')
{
  echo "# Baseline comparison"
  echo
  echo "Generated by \`scripts/baseline.sh\` from \`src/baseline_tests.rs\` (the test fails if any row changes)."
  echo "The baseline is the usual agent-spending guard: the agent may pay any address on an allowlist"
  echo "(every supplier's registered address), within the same per-payment and per-period limits as the contract."
  echo
  echo "$table"
  echo
  echo "$summary"
} > docs/baseline.md
echo "$table"
echo
echo "$summary"
echo
echo "Saved to docs/baseline.md"
